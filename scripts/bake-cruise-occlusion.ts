import {createHash} from 'node:crypto';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {BufferAttribute,type BufferGeometry} from 'three';
import {buildCruiseGeometry} from '../src/cruise.ts';
import {bakeCabinOcclusion,CABIN_ATLAS_BYTES} from '../src/occlusion.ts';

if(process.argv.slice(2).some(argument=>argument!=='--check'))throw new Error('Usage: bake-cruise-occlusion.ts [--check]');
const check=process.argv.includes('--check'),root=new URL('../',import.meta.url),destination=new URL('src/generated/',root);
const sha=(bytes:Uint8Array|string)=>createHash('sha256').update(bytes).digest('hex');
const bytesOf=(array:ArrayBufferView)=>Buffer.from(array.buffer,array.byteOffset,array.byteLength);
const inputs=createHash('sha256');
function field(name:string,value:Uint8Array|string) {
  const bytes=typeof value==='string'?Buffer.from(value):value;
  inputs.update(JSON.stringify([name,bytes.byteLength])+'\n');inputs.update(bytes);
}
function geometries(name:string,items:BufferGeometry[]) {
  field(name,JSON.stringify(items.length));
  items.forEach((geometry,index)=>{
    for(const key of ['position','index'] as const) {
      const attribute=key==='index'?geometry.index:geometry.getAttribute(key);
      if(!attribute){field(`${name}/${index}/${key}`,'null');continue;}
      if(!(attribute instanceof BufferAttribute))throw new Error('Interleaved bake inputs need explicit serialization');
      field(`${name}/${index}/${key}/layout`,JSON.stringify([attribute.array.constructor.name,attribute.itemSize,attribute.count,attribute.normalized]));
      field(`${name}/${index}/${key}/bytes`,bytesOf(attribute.array));
    }
  });
}
// Include the real algorithm, chart layout, sample count, rounding and dependency versions.
field('occlusion.ts',await readFile(new URL('src/occlusion.ts',root)));
const lock=JSON.parse(await readFile(new URL('package-lock.json',root),'utf8'));
for(const dependency of ['three','three-mesh-bvh']) {
  const installed=JSON.parse(await readFile(new URL(`node_modules/${dependency}/package.json`,root),'utf8'));
  if(installed.version!==lock.packages[`node_modules/${dependency}`].version)throw new Error(`Unexpected installed ${dependency} version`);
  field(dependency,installed.version);
}
let calls=0;
const ship=buildCruiseGeometry((blockers,floor,cabin,aft)=>{
  if(++calls!==1||!aft)throw new Error('Expected one complete side and aft cabin bake');
  field('chart-placement',JSON.stringify({floor,cabin,aftFront:aft.front}));
  geometries('side',blockers);geometries('aft',aft.blockers);
  return bakeCabinOcclusion(blockers,floor,cabin,aft);
});
if(calls!==1)throw new Error('Cruise factory did not supply the visibility inputs');
const texture=ship.paint[0].aoMap!,pixels=texture.image.data as Uint8Array;
if(pixels.byteLength!==CABIN_ATLAS_BYTES)throw new Error('Unexpected cabin atlas length');
const metadata={format:'rgba8',width:texture.image.width,height:texture.image.height,byteLength:pixels.byteLength,sha256:sha(pixels),inputSha256:inputs.digest('hex')};
const source=`// Generated by npm run bake:cabin. Check with npm run check:cabin.\nexport const CRUISE_OCCLUSION = ${JSON.stringify(metadata,null,2)} as const;\n`;
const atlasPath=new URL('cruise-occlusion.rgba',destination),metadataPath=new URL('cruise-occlusion.ts',destination);
if(check) {
  const stored=await readFile(atlasPath),storedSource=await readFile(metadataPath,'utf8');
  if(!stored.equals(bytesOf(pixels))||storedSource!==source)throw new Error('Stale cabin visibility data. Run npm run bake:cabin and review the changed inputs and bytes.');
}else {
  await mkdir(destination,{recursive:true});await writeFile(atlasPath,pixels);await writeFile(metadataPath,source);
}
console.log(JSON.stringify({mode:check?'check':'generate',...metadata}));
